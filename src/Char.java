public class Char {
    public static void main(String[] args) {
        // char é um tipo de dado primitivo em Java que representa um único caractere Unicode.
        // Ele é declarado usando aspas simples (' ') e pode armazenar letras, dígitos, símbolos 
        // ou caracteres especiais.
        char letra = 'M';
        char simbolo = '©';
        char digito = '7';
        
        System.out.println("Letra: " + letra);
        System.out.println("Símbolo: " + simbolo);
        System.out.println("Dígito: " + digito);

    }
}